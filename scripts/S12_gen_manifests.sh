#!/usr/bin/env bash
# S8_gen_manifests.sh — emit one Deployment per cell of the Table 8a matrix.
#
# Every manifest is identical except for name, label, image and run uid, so that
# base image and compression flag are the only factors that vary.
#
# Deployments start at replicas: 0. They consume no node capacity until
# S8_upx_matrix.sh scales them, which matters because the sweep runs alongside
# the ~14 deployments already in the namespace.
#
# usage: bash scripts/S8_gen_manifests.sh [outdir]
set -euo pipefail

OUT="${1:-frameworks/quarkus/native/matrix}"
NS="${NS:-perf-test}"
REGISTRY="${REGISTRY:-ghcr.io/matejsaric32}"
PREFIX="${PREFIX:-quarkus-perf-mx}"
TAG="${TAG:-latest}"
# IfNotPresent works whether the images were pushed to the registry or imported
# straight into containerd with `k3s ctr images import`.
PULL="${PULL:-IfNotPresent}"

mkdir -p "$OUT"

# base | run uid
BASES="ubi|1001 micro|1001 distroless|65532"
COMPS="c0 c9 cbest clzma"

n=0
for b in $BASES; do
  bn="${b%%|*}"; uid="${b##*|}"
  for cn in $COMPS; do
    cell="${bn}-${cn}"
    name="${PREFIX}-${cell}"
    f="$OUT/${name}-deployment.yaml"
    cat > "$f" <<YAML
# Generated by scripts/S8_gen_manifests.sh — do not edit by hand.
# Table 8a cell: base=${bn} compression=${cn}
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${name}
  namespace: ${NS}
  labels:
    experiment: table8a
    base: ${bn}
    compression: ${cn}
spec:
  # Scaled by scripts/S8_upx_matrix.sh; idle at 0 so the matrix costs nothing
  # until it is being measured.
  replicas: 0
  selector:
    matchLabels:
      app: ${name}
  template:
    metadata:
      labels:
        # Unique per variant. S4_upx_pagemap_analysis.sh warns that the older
        # manifests reuse 'app' across native variants, which makes a label
        # selector silently match the wrong pods.
        app: ${name}
        experiment: table8a
        base: ${bn}
        compression: ${cn}
      annotations:
        prometheus.io/scrape: "true"
        prometheus.io/port: "8080"
        prometheus.io/path: "/q/metrics"
    spec:
      containers:
        - name: ${name}
          image: ${REGISTRY}/${PREFIX}-${cell}:${TAG}
          imagePullPolicy: ${PULL}
          ports:
            - containerPort: 8080
          envFrom:
            - configMapRef:
                name: quarkus-perf-config
            - secretRef:
                name: perf-secret
          securityContext:
            # uid 1001 does not exist in quarkus-distroless-image:2.0, whose
            # unprivileged account is nonroot=65532. Set explicitly so the pod
            # spec states the run user rather than inheriting it from the image.
            runAsUser: ${uid}
          resources:
            requests:
              memory: "512Mi"
              cpu: "500m"
            limits:
              memory: "1Gi"
              cpu: "1000m"
          livenessProbe:
            httpGet:
              path: /q/health/live
              port: 8080
            initialDelaySeconds: 0
            periodSeconds: 10
            failureThreshold: 3
          readinessProbe:
            httpGet:
              path: /q/health/ready
              port: 8080
            initialDelaySeconds: 0
            periodSeconds: 10
            failureThreshold: 3
YAML
    n=$((n+1))
    echo "  $f"
  done
done
echo "generated $n manifests in $OUT"
